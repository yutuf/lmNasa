from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import yaml

SITES_FILE = Path(__file__).resolve().parent.parent / "data" / "sites.yaml"
DERIVED_FILE = SITES_FILE.with_name("derived_sites.yaml")   # generated by scripts/derive_best_points.py


@dataclass
class Site:
    id: str
    name: str
    lat: float
    lon: float
    category: str = "custom"
    note: str = ""
    source: str = ""
    verified: bool = False
    reference: bool = False   # shown for comparison, never ranked
    # derived points (computed by LunaNav near a cited site, NOT published coordinates)
    derived_from: str = ""
    distance_m: float | None = None
    bearing_deg: float | None = None
    slope_deg: float | None = None
    cited_slope_deg: float | None = None

    @property
    def derived(self) -> bool:
        return bool(self.derived_from)


def load_sites(path: str | Path = SITES_FILE, include_derived: bool = True) -> list[Site]:
    """Cited sites; each derived point (if generated) is placed right after its parent."""
    cited = [Site(**s) for s in yaml.safe_load(Path(path).read_text())["sites"]]
    derived_file = Path(path).with_name(DERIVED_FILE.name)
    if not include_derived or not derived_file.exists():
        return cited
    derived = [Site(**s) for s in (yaml.safe_load(derived_file.read_text()) or {}).get("sites", [])]
    out = []
    for c in cited:
        out.append(c)
        out.extend(d for d in derived if d.derived_from == c.id)
    return out

"""Print a symbol's pin numbers and names from KiCad's own symbol library.

The boards in this folder are generated by scripts and have no schematic, so this is how a pin
mapping is checked against something other than memory:

  python hardware/tools/kicad_pins.py RF_Module ESP32-C3-DevKitM-1
  python hardware/tools/kicad_pins.py LED WS2812B

Works with any Python (no KiCad modules needed). Set KICAD_SYMBOLS if KiCad is installed elsewhere.
"""
import os
import re
import sys
from pathlib import Path

SYMBOLS = Path(os.environ.get("KICAD_SYMBOLS", r"C:\Program Files\KiCad\10.0\share\kicad\symbols"))


def symbol_block(text: str, name: str) -> str:
    """The balanced s-expression of the top-level symbol called `name`."""
    start = text.find(f'(symbol "{name}"')
    if start < 0:
        raise SystemExit(f"symbol {name!r} not found")
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return text[start:i + 1]
    raise SystemExit("unbalanced symbol file")


def pins(library: str, name: str, _seen=None) -> list[tuple[str, str, str]]:
    """[(number, name, electrical type)], following `extends` to the parent symbol."""
    text = (SYMBOLS / f"{library}.kicad_sym").read_text(encoding="utf-8")
    block = symbol_block(text, name)
    found = re.findall(r'\(pin\s+(\w+)\s+\w+.*?\(name\s+"([^"]*)".*?\(number\s+"([^"]*)"', block, re.S)
    if not found:
        parent = re.search(r'\(extends\s+"([^"]+)"\)', block)
        if parent and parent.group(1) != name:
            return pins(library, parent.group(1))
    return [(number, pin_name, kind) for kind, pin_name, number in found]


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    rows = pins(sys.argv[1], sys.argv[2])

    def order(row):
        return (0, int(row[0])) if row[0].isdigit() else (1, row[0])

    for number, pin_name, kind in sorted(rows, key=order):
        print(f"{number:>4}  {pin_name:<24} {kind}")
    print(f"{len(rows)} pins")


if __name__ == "__main__":
    main()

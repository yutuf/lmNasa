"""Turn a site's precomputed Sun/Earth series into the LED animation for the horizon compass.

Reads data/series/<site>.npz (written by precompute.py or the derive scripts) and writes a C header
for hardware/horizon_compass/firmware: one entry per hour with the LED that points at the Sun, its
brightness (visible fraction of the solar disk above the terrain) and the LED that points at Earth
(lit only while Earth's centre is above the terrain).

  python scripts/export_compass_track.py malapert_massif_region_best --start 2027-09-09 --days 30

LED numbering matches hardware/horizon_compass/generate_board.py: index 0 is D1 at north and the
chain runs counter-clockwise, so index k sits at azimuth -15 * k degrees.
"""
import argparse
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from lunanav.series import load_series

N_LEDS = 24
DEFAULT_OUT = Path(__file__).resolve().parents[1] / "hardware" / "horizon_compass" / "firmware" / "track.h"


def led_index(az_deg, n_leds=N_LEDS):
    """LED nearest to an azimuth (degrees clockwise from north) on the counter-clockwise chain."""
    return np.rint(-np.asarray(az_deg, dtype=float) / (360.0 / n_leds)).astype(int) % n_leds


def c_array(name, values, per_line=24):
    rows = [", ".join(f"{int(v):3d}" for v in values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return f"const uint8_t {name}[TRACK_HOURS] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("site", help="site id with a series in data/series")
    ap.add_argument("--start", default="2027-09-09", help="UTC start date, ISO format")
    ap.add_argument("--days", type=float, default=30.0, help="length of the animation in days (1 h per frame)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    vis, _step_h, _terrain = load_series(args.site)
    if vis is None:
        raise SystemExit(f"no series for {args.site!r} in data/series")
    times = vis.times_utc.astype("datetime64[s]").astype(np.int64)
    start = int(datetime.fromisoformat(args.start).replace(tzinfo=timezone.utc).timestamp())
    sel = (times >= start) & (times < start + int(args.days * 86400))
    if not sel.any():
        first, last = (datetime.fromtimestamp(int(t), timezone.utc).date() for t in (times[0], times[-1]))
        raise SystemExit(f"no data in that window; the series covers {first} to {last}")

    sun_led = led_index(vis.sun_az[sel])
    sun_level = np.rint(np.clip(vis.sun_fraction[sel], 0.0, 1.0) * 255).astype(int)
    earth_led = led_index(vis.earth_az[sel])
    earth_on = vis.earth_visible[sel].astype(int)

    header = (
        f"// Generated by scripts/export_compass_track.py: do not edit.\n"
        f"// Site: {args.site}   start: {args.start} UTC   frames: {int(sel.sum())} (1 h each)\n"
        f"// LED index 0 = D1 (north); the chain runs counter-clockwise, {360 // N_LEDS} degrees per LED.\n"
        f"#pragma once\n#include <stdint.h>\n\n"
        f"#define TRACK_LEDS {N_LEDS}\n#define TRACK_HOURS {int(sel.sum())}\n\n"
    )
    body = (c_array("SUN_LED", sun_led) + "\n" + c_array("SUN_LEVEL", sun_level) + "\n"
            + c_array("EARTH_LED", earth_led) + "\n" + c_array("EARTH_ON", earth_on))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(header + body, encoding="utf-8", newline="\n")
    print(f"{args.out}: {int(sel.sum())} frames, Sun lit {100 * (sun_level > 0).mean():.0f} % of them, "
          f"Earth in view {100 * earth_on.mean():.0f} %")


if __name__ == "__main__":
    main()

"""Offline: best landing point INSIDE each Artemis III region -> data/derived_sites.yaml.

usage: python scripts/derive_region_best.py path/to/LDEM_80S_40MPP_ADJ.TIF path/to/usgs_grids/
                                            [--max-candidates 1500] [--top 5] [--refine-spacing 100]
                                            [--refine-radius 600] [--max-slope 10] [--regions Haworth ...]

The 1 km search of derive_best_points.py often stops at its own edge: a region is
~20 x 20 km. This script searches the whole region as NASA/USGS define it (the
USGS 1 km navigation grid, McClernan 2024, doi:10.5066/P1MEQ6UK):

  1. coarse grid clipped to the region, spacing chosen so that about
     --max-candidates points are tried (e.g. 550 m for a 441 km2 region),
  2. candidates steeper than --max-slope dropped (40 m baseline),
  3. 360 deg horizon + Sun/Earth series for each (the region's site series is
     rotated into each candidate's frame, as in derive_best_points.py),
  4. the --top best are refined on a --refine-spacing grid within --refine-radius,
     still clipped to the region,
  5. objective: share of hours with Sun (>= 50 % of the disk) AND Earth in view,
     tie-break sunlight, then closeness to the region's site.

The result is a separate site "<site>_region_best" (search: region) next to the
1 km derived point; neither script removes the other's result. Costs ~2000
horizons per region (a few minutes each on a laptop).
Needs: DEM, the USGS grids, and data/series/<site>.npz of each region's site.
"""
import argparse
import sys
import time
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from lunanav.derive import candidate_grid, rank_candidates, score_point, slope_deg  # noqa: E402
from lunanav.geometry import distance_bearing  # noqa: E402
from lunanav.horizon import compute_horizon, dem_sampler, load_profiles, save_profiles  # noqa: E402
from lunanav.regions import REGIONS, RegionGrid, find_regions, parent_site_id  # noqa: E402
from lunanav.series import load_series  # noqa: E402
from lunanav.sites import load_sites  # noqa: E402

COMPASS8 = ["N", "NE", "E", "SE", "S", "SW", "W", "NW"]
HEADER = ("# GENERATED by scripts/derive_best_points.py and scripts/derive_region_best.py -\n"
          "# computed points, NOT published coordinates.\n")


def coarse_spacing(area_km2, max_candidates, floor_m=250.0):
    """Grid spacing (m, multiple of 50) giving about max_candidates points over the area."""
    return max(floor_m, float(np.ceil(np.sqrt(area_km2 * 1e6 / max_candidates) / 50.0) * 50.0))


def search_region(grid, vis, lat0, lon0, horizon_fn, sample, a, log=print):
    """Coarse-to-fine search inside `grid`. Returns (best CandidateScore, n_evaluated, spacing)."""
    spacing = coarse_spacing(grid.area_km2, a.max_candidates)
    x, y = grid.grid_points(spacing)
    la, lo = grid.to_latlon(x, y)
    d, b = distance_bearing(lat0, lon0, la, lo)
    coarse = rank_candidates(vis, lat0, lon0, (la, lo, d, b), horizon_fn, sample, a.max_slope)
    log(f"{'':22s} coarse: {len(la)} points at {spacing:.0f} m, {len(coarse)} under {a.max_slope:.0f} deg")
    if not coarse:
        return None, len(la), spacing
    pool, n_eval = list(coarse), len(la)
    for c in coarse[:a.top]:
        rla, rlo, _, _ = candidate_grid(c.lat, c.lon, a.refine_radius, a.refine_spacing)
        inside = grid.contains(*grid.to_xy(rla, rlo))
        rla, rlo = rla[inside], rlo[inside]
        rd, rb = distance_bearing(lat0, lon0, rla, rlo)
        pool += rank_candidates(vis, lat0, lon0, (rla, rlo, rd, rb), horizon_fn, sample, a.max_slope)
        n_eval += len(rla)
    pool.sort(key=lambda c: (c.both_frac, c.sun_frac, -c.distance_m), reverse=True)
    return pool[0], n_eval, spacing


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("dem")
    ap.add_argument("grids", help="folder with the USGS 1 km grid shapefiles (+ .prj)")
    ap.add_argument("--max-candidates", type=int, default=1500)
    ap.add_argument("--top", type=int, default=5, help="coarse winners to refine")
    ap.add_argument("--refine-spacing", type=float, default=100.0)
    ap.add_argument("--refine-radius", type=float, default=600.0)
    ap.add_argument("--max-slope", type=float, default=10.0)
    ap.add_argument("--step", type=float, default=120.0, help="horizon ray step, m")
    ap.add_argument("--max-km", type=float, default=150.0, help="horizon ray length, km")
    ap.add_argument("--regions", nargs="*", help="only these USGS region tokens, e.g. Haworth Slater_Plain")
    ap.add_argument("--data", default=str(ROOT / "data"))
    a = ap.parse_args(argv)

    sample = dem_sampler(a.dem)
    dem_name = Path(a.dem).name
    data = Path(a.data)
    hz_path, series_dir, derived_path = data / "horizons.json", data / "series", data / "derived_sites.yaml"
    profiles = load_profiles(hz_path) if hz_path.exists() else {}
    entries = (yaml.safe_load(derived_path.read_text()) or {}).get("sites", []) if derived_path.exists() else []
    sites = {s.id: s for s in load_sites(data / "sites.yaml", include_derived=False)}

    def horizon_at(lat, lon, sid="candidate"):
        return compute_horizon(sample, sid, float(lat), float(lon), step_m=a.step,
                               max_distance_m=a.max_km * 1000, source=dem_name)

    written = []
    for reg, files in sorted(find_regions(Path(a.grids)).items()):
        if a.regions and reg not in a.regions:
            continue
        pid = parent_site_id(reg)
        parent = sites.get(pid)
        vis, step_h, _ = load_series(pid, series_dir) if parent else (None, None, None)
        if parent is None or vis is None:
            print(f"{reg:22s} skipped: site {pid} {'not in sites.yaml' if parent is None else 'has no series yet'}")
            continue
        t0 = time.time()
        grid = RegionGrid.from_shapefiles(reg, files)
        print(f"{reg:22s} {grid.area_km2:.0f} km2, site {pid}")
        best, n_eval, spacing = search_region(grid, vis, parent.lat, parent.lon, horizon_at, sample, a)
        if best is None:
            print(f"{'':22s} no point under {a.max_slope:.0f} deg in the region; nothing written")
            continue
        p_hz = horizon_at(parent.lat, parent.lon, pid)    # same DEM + settings: fair comparison
        pz = score_point(vis, parent.lat, parent.lon, parent.lat, parent.lon, p_hz)
        p_lit = pz["sun_fraction"] >= 0.5
        p_both = float((p_lit & pz["earth_visible"]).mean())
        p_slope = float(slope_deg(sample, parent.lat, parent.lon)[0])
        direction = COMPASS8[int((best.bearing_deg + 22.5) // 45) % 8]
        print(f"{'':22s} {n_eval} points in {time.time() - t0:.0f} s | site: both {p_both:.1%} slope {p_slope:.1f} | "
              f"best: both {best.both_frac:.1%} sun {best.sun_frac:.1%} earth {best.earth_frac:.1%} "
              f"slope {best.slope_deg:.1f} at {best.distance_m / 1000:.1f} km {direction}")

        did = f"{pid}_region_best"
        hz = horizon_at(best.lat, best.lon, did)
        profiles[did] = hz
        z = score_point(vis, parent.lat, parent.lon, best.lat, best.lon, hz)
        np.savez_compressed(
            series_dir / f"{did}.npz",
            times=vis.times_utc.astype("datetime64[s]").astype("int64"), step_h=step_h,
            **{k: np.asarray(v, dtype=bool if k == "earth_visible" else "float32") for k, v in z.items()},
            terrain=f"{dem_name} (derived point, region search)")
        site_word = "region centre" if parent.category == "region_centre" else "published point"
        entries = [e for e in entries if e["id"] != did]
        entries.append(dict(
            id=did, name=f"{REGIONS[reg][1]} — best point in the Artemis III region",
            lat=round(best.lat, 5), lon=round(best.lon, 5), category="derived", derived_from=pid,
            search="region", distance_m=round(best.distance_m), bearing_deg=round(best.bearing_deg, 1),
            slope_deg=round(best.slope_deg, 1), cited_slope_deg=round(p_slope, 1),
            note=(f"Computed by LunaNav, not from a publication: best of {n_eval} points inside the USGS "
                  f"{REGIONS[reg][1]} grid ({grid.area_km2:.0f} km2; {spacing:.0f} m grid, then "
                  f"{a.refine_spacing:.0f} m around the top {a.top}), slope <= {a.max_slope:.0f} deg; "
                  f"{best.distance_m / 1000:.1f} km {direction} of the {site_word}. Objective: hours with Sun and "
                  f"Earth both in view, {best.both_frac:.1%} vs {p_both:.1%} at the {site_word} "
                  f"({vis.times_utc[0].astype('datetime64[D]')} to {vis.times_utc[-1].astype('datetime64[D]')})."),
            source=f"derived from {pid} with {dem_name} inside {', '.join(f.name for f in files)}",
            verified=False))
        written.append(did)

    save_profiles(list(profiles.values()), hz_path)
    derived_path.write_text(HEADER + yaml.safe_dump({"sites": entries}, sort_keys=False, allow_unicode=True))
    print(f"wrote {len(written)} region-best point(s) to {derived_path}")
    return written


if __name__ == "__main__":
    main()

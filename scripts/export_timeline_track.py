"""Turn three sites' precomputed Sun/Earth series into the LED data for the timeline bar.

The bar (hardware/timeline_bar) has three rows of 28 LEDs: a row is one landing spot, an LED is one
Earth day. Per site and day this script computes

  sun share   = fraction of that day's hours with at least half the solar disk above the terrain
                (sun_fraction >= 0.5)
  earth share = fraction of that day's hours with Earth's centre above the terrain (earth_visible)

scales both to 0..255 and writes hardware/timeline_bar/firmware/track.h with SUN_SHARE and
EARTH_SHARE in LED chain order.

  python scripts/export_timeline_track.py                      # the three Malapert Massif demo spots
  python scripts/export_timeline_track.py site_a site_b site_c --start 2027-09-09 --days 28

Chain order matches hardware/timeline_bar/generate_board.py: row A runs left to right (day 1 first),
row B right to left (day 28 first), row C left to right. With fewer than 28 days the remaining LEDs
of each row stay dark.
"""
import argparse
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from lunanav.series import load_series

N_ROWS = 3
N_DAYS = 28
ROW_NAMES = "ABC"
DEFAULT_SITES = ["malapert_massif", "malapert_massif_derived", "malapert_massif_region_best"]
REPO = Path(__file__).resolve().parents[1]
DEFAULT_OUT = REPO / "hardware" / "timeline_bar" / "firmware" / "track.h"


def chain_index(row, day):
    """LED position in the data chain for row 0..2 and day 1..28 (serpentine: row B is reversed)."""
    return row * N_DAYS + ((day - 1) if row % 2 == 0 else (N_DAYS - day))


def daily_shares(site, start_s, days):
    """(sun share, earth share) per day, each an array of `days` values in 0..1."""
    vis, _step_h, _terrain = load_series(site)
    if vis is None:
        raise SystemExit(f"no series for {site!r} in data/series")
    times = vis.times_utc.astype("datetime64[s]").astype(np.int64)
    sun_up = np.asarray(vis.sun_fraction) >= 0.5
    earth_up = np.asarray(vis.earth_visible).astype(bool)
    sun, earth = np.zeros(days), np.zeros(days)
    for d in range(days):
        sel = (times >= start_s + d * 86400) & (times < start_s + (d + 1) * 86400)
        if not sel.any():
            first, last = (datetime.fromtimestamp(int(t), timezone.utc).date() for t in (times[0], times[-1]))
            raise SystemExit(f"{site}: no data for day {d + 1}; the series covers {first} to {last}")
        sun[d] = sun_up[sel].mean()
        earth[d] = earth_up[sel].mean()
    return sun, earth


def c_array(name, values, row_comments):
    rows = []
    for row, comment in enumerate(row_comments):
        chunk = values[row * N_DAYS:(row + 1) * N_DAYS]
        rows.append(f"  // {comment}\n  " + ", ".join(f"{int(v):3d}" for v in chunk))
    return f"const uint8_t {name}[TRACK_LEDS] = {{\n" + ",\n".join(rows) + "\n};\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sites", nargs="*", default=DEFAULT_SITES, help="three site ids with a series in data/series (rows A, B, C)")
    ap.add_argument("--start", default="2027-09-09", help="UTC start date, ISO format")
    ap.add_argument("--days", type=int, default=N_DAYS, help=f"days to show, 1..{N_DAYS} (one LED per day)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    if len(args.sites) != N_ROWS:
        raise SystemExit(f"the bar has {N_ROWS} rows: give exactly {N_ROWS} site ids (got {len(args.sites)})")
    if not 1 <= args.days <= N_DAYS:
        raise SystemExit(f"--days must be 1..{N_DAYS}: each row has {N_DAYS} LEDs")

    start_s = int(datetime.fromisoformat(args.start).replace(tzinfo=timezone.utc).timestamp())
    sun_chain = np.zeros(N_ROWS * N_DAYS, dtype=int)
    earth_chain = np.zeros(N_ROWS * N_DAYS, dtype=int)
    summary = []
    for row, site in enumerate(args.sites):
        sun, earth = daily_shares(site, start_s, args.days)
        for d in range(args.days):
            k = chain_index(row, d + 1)
            sun_chain[k] = int(np.rint(sun[d] * 255))
            earth_chain[k] = int(np.rint(earth[d] * 255))
        summary.append(
            f"row {ROW_NAMES[row]} {site}: Sun on {int((sun > 0).sum())} of {args.days} days "
            f"(mean share {100 * sun.mean():.1f} %), Earth on {int((earth > 0).sum())} of {args.days} days "
            f"(mean share {100 * earth.mean():.1f} %)"
        )

    comments = [
        f"row {ROW_NAMES[row]}: {site}, " + ("day 1 -> 28" if row % 2 == 0 else "day 28 -> 1 (row runs right to left)")
        for row, site in enumerate(args.sites)
    ]
    header = (
        f"// Generated by scripts/export_timeline_track.py: do not edit.\n"
        f"// Start: {args.start} UTC   days: {args.days}   one LED per Earth day, values 0..255\n"
        f"// SUN_SHARE   = share of the day's hours with sun_fraction >= 0.5 (half the solar disk above the terrain)\n"
        f"// EARTH_SHARE = share of the day's hours with Earth's centre above the terrain\n"
        f"// LED chain order: index 0 = D1 (row A, day 1). Row A left to right, row B right to left, row C left to right.\n"
        f"#pragma once\n#include <stdint.h>\n\n"
        f"#define TRACK_ROWS {N_ROWS}\n#define TRACK_DAYS {N_DAYS}\n#define TRACK_LEDS {N_ROWS * N_DAYS}\n\n"
    )
    body = c_array("SUN_SHARE", sun_chain, comments) + "\n" + c_array("EARTH_SHARE", earth_chain, comments)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(header + body, encoding="utf-8", newline="\n")

    out = args.out.resolve()
    shown = out.relative_to(REPO).as_posix() if out.is_relative_to(REPO) else str(out)
    print(f"{shown}: {N_ROWS * N_DAYS} LEDs, start {args.start} UTC, {args.days} days")
    for line in summary:
        print(line)


if __name__ == "__main__":
    main()
